// Especies y razas. Al empezar se elige especie (perro, gato o monstruo)
// y el huevo trae una raza al azar, que no se ve hasta que nace.
//
// Cada raza es un plano en datos: proporciones, hocico, orejas, pelo,
// cola y sus capas (colores y dónde va cada uno). El escultor de la
// escena (public/js/scene/pet.js) lo convierte en una figura. Todo son
// números entre 0 y 1 salvo que se diga otra cosa.
//
//   size: tamaño de la raza (0 toy, 1 gigante).
//   body: chunk (robusto), leg (largo de patas), chest (pecho), long (lomo).
//   head: size (cabeza respecto al cuerpo), dome (cráneo abombado),
//         width (ancho de cara).
//   snout: len, width, drop (belfos colgantes), stop (escalón frente-hocico).
//   ears: type y size (ver EAR_TYPES); set: altura en la cabeza.
//   coat: tipo de pelo (ver COAT_TYPES).
//   tail: type y size (ver TAIL_TYPES).
//   extras: rasgos sueltos (arrugas, barba, cejas, moño…).
//   coats: capas posibles. `base` es el color de fondo; `paint` pinta
//          zonas encima, en orden (ver REGIONS en pet.js).
//   eyes: colores de iris posibles.

